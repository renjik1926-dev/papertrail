"""Calendar export (BUILD_PLAN §8.10).

One all-day VEVENT per shown deadline that has a due date, with reminders 7 days and 1 day
before. Deadlines without a resolvable date are left out (the print page lists them).
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping
from datetime import date, datetime, timedelta
from typing import Any

from icalendar import Alarm, Calendar, Event

UID_DOMAIN = "papertrail.local"


def is_exportable(item: Mapping[str, Any]) -> bool:
    return (
        item["kind"] == "deadline"
        and item["status"] in ("verified", "needs_review")
        and item["review_state"] != "dismissed"
    )


def first_page(item: Mapping[str, Any]) -> int | None:
    rects = item.get("rects") or []
    return int(rects[0]["page_no"]) if rects else None


def build_calendar(
    items: Iterable[Mapping[str, Any]], *, document_name: str, stamp: datetime
) -> tuple[bytes, int]:
    """Return (ics bytes, number of deadlines left out because they have no date)."""
    calendar = Calendar()
    calendar.add("prodid", "-//PaperTrail//papertrail//EN")
    calendar.add("version", "2.0")
    calendar.add("calscale", "GREGORIAN")
    skipped = 0
    for item in items:
        if not is_exportable(item):
            continue
        if not item.get("due_date"):
            skipped += 1
            continue
        due = date.fromisoformat(item["due_date"])
        event = Event()
        event.add("uid", f"{item['item_key']}@{UID_DOMAIN}")
        event.add("dtstamp", stamp)
        event.add("dtstart", due)
        event.add("dtend", due + timedelta(days=1))
        event.add("summary", f"Due: {item['text']}")
        lines = [item["text"]]
        if item["status"] != "verified":
            lines[0] += " (needs review)"
        lines.append(f'From the letter: "{item["quote"]}"')
        page = first_page(item)
        if page is not None:
            lines.append(f"Page {page} of {document_name}")
        if item.get("due_calc"):
            lines.append(f"Calculated: {item['due_calc']}")
        lines.append("Generated by PaperTrail. Check this against the original letter.")
        event.add("description", "\n".join(lines))
        for days in (7, 1):
            alarm = Alarm()
            alarm.add("action", "DISPLAY")
            alarm.add("description", f"Due: {item['text']}")
            alarm.add("trigger", timedelta(days=-days))
            event.add_component(alarm)
        calendar.add_component(event)
    return calendar.to_ical(), skipped
